#!/usr/bin/env python3
"""Join EARS requirements with test results into a STATUS.md report."""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HEADING_ID = re.compile(r"^#{2,4}\s+(N?FR-[A-Z][A-Z0-9]*-\d{4})\b[ \t]*(.*)$")
# Test names may use underscores and any case: test_fr_auth_0001_login, TestFR_AUTH_0001.
TEST_ID = re.compile(r"(N?FR)[-_]([A-Z][A-Z0-9]*)[-_](\d{4})(?!\d)", re.IGNORECASE)

PASSING, FAILING, WIP, UNTESTED = "✅", "❌", "🚧", "⚪"
UNKNOWN = "⚠"


def load_requirements(req_dir: Path, output: Path) -> dict[str, dict]:
    requirements = {}
    for path in sorted(req_dir.glob("*.md")):
        if path.resolve() == output.resolve():
            continue
        for line in path.read_text(encoding="utf-8").splitlines():
            match = HEADING_ID.match(line)
            if not match:
                continue
            req_id, title = match.groups()
            if req_id in requirements:
                sys.exit(f"duplicate requirement {req_id} in {path} and {requirements[req_id]['file']}")
            requirements[req_id] = {"title": title.strip(), "file": path}
    if not requirements:
        sys.exit(f"no requirement headings (### FR-<DOMAIN>-NNNN Title) found in {req_dir}")
    return requirements


def parse_junit(path: Path, text: str) -> list[tuple[str, str]]:
    try:
        root = ET.fromstring(text)
    except ET.ParseError as err:
        sys.exit(f"{path}: invalid JUnit XML: {err}")
    results = []
    for case in root.iter("testcase"):
        name = " ".join(filter(None, [case.get("classname"), case.get("name")]))
        if case.find("failure") is not None or case.find("error") is not None:
            status = "fail"
        elif case.find("skipped") is not None:
            status = "skip"
        else:
            status = "pass"
        results.append((name, status))
    return results


def parse_go_json(path: Path, text: str) -> list[tuple[str, str]]:
    final = {}
    for lineno, line in enumerate(text.splitlines(), 1):
        if not line.strip():
            continue
        try:
            event = json.loads(line)
        except json.JSONDecodeError:
            sys.exit(f"{path}:{lineno}: not a `go test -json` event: {line[:80]}")
        if event.get("Test") and event.get("Action") in ("pass", "fail", "skip"):
            final[(event.get("Package", ""), event["Test"])] = event["Action"]
    return [(f"{pkg} {test}", status) for (pkg, test), status in final.items()]


def load_results(paths: list[Path]) -> list[tuple[str, str]]:
    results = []
    for path in paths:
        text = path.read_text(encoding="utf-8")
        parse = parse_junit if text.lstrip().startswith("<") else parse_go_json
        results.extend(parse(path, text))
    return results


def ids_in(name: str) -> list[str]:
    return sorted({"-".join(m.groups()).upper() for m in TEST_ID.finditer(name)})


def build_status(requirements: dict, results: list[tuple[str, str]]):
    tests = {req_id: [] for req_id in requirements}
    unknown = {}
    for name, status in results:
        for req_id in ids_in(name):
            if req_id in tests:
                tests[req_id].append((name, status))
            else:
                unknown.setdefault(req_id, []).append(name)

    status = {}
    for req_id, cases in tests.items():
        outcomes = {s for _, s in cases}
        if not cases:
            status[req_id] = UNTESTED
        elif "fail" in outcomes:
            status[req_id] = FAILING
        elif "skip" in outcomes:
            status[req_id] = WIP
        else:
            status[req_id] = PASSING
    return status, tests, unknown


def domain_of(req_id: str) -> str:
    return req_id.split("-")[1]


def render(requirements, status, tests, unknown, output: Path) -> str:
    domains = sorted({domain_of(r) for r in requirements})
    icons = [PASSING, FAILING, WIP, UNTESTED]
    lines = [
        "# Requirement Status",
        "",
        "Generated by `requirements-status` from test results. Do not edit by hand.",
        "",
        "| Domain | ✅ Passing | ❌ Failing | 🚧 In progress | ⚪ No test |",
        "|--------|-----------|-----------|---------------|-----------|",
    ]
    for domain in domains:
        counts = [sum(1 for r, s in status.items() if domain_of(r) == domain and s == icon) for icon in icons]
        lines.append(f"| {domain} | " + " | ".join(map(str, counts)) + " |")
    totals = [sum(1 for s in status.values() if s == icon) for icon in icons]
    lines.append("| **Total** | " + " | ".join(f"**{n}**" for n in totals) + " |")

    lines += ["", "## Needs attention", ""]
    attention = []
    for icon in (FAILING, WIP, UNTESTED):
        for req_id in sorted(r for r, s in status.items() if s == icon):
            attention.append(f"- {icon} {req_id} {requirements[req_id]['title']}".rstrip())
            if icon == FAILING:
                attention += [f"  - failing: `{name}`" for name, s in tests[req_id] if s == "fail"]
    for req_id in sorted(unknown):
        attention.append(f"- {UNKNOWN} {req_id} is not a requirement; referenced by:")
        attention += [f"  - `{name}`" for name in sorted(unknown[req_id])]
    lines += attention or ["Nothing. Every requirement has passing tests."]

    lines += ["", "## All requirements"]
    for domain in domains:
        files = sorted({requirements[r]["file"] for r in requirements if domain_of(r) == domain})
        links = ", ".join(f"[{f.name}]({Path(os.path.relpath(f, output.parent)).as_posix()})" for f in files)
        lines += ["", f"### {domain} ({links})", "", "| | ID | Requirement |", "|---|----|-------------|"]
        for req_id in sorted(r for r in requirements if domain_of(r) == domain):
            lines.append(f"| {status[req_id]} | {req_id} | {requirements[req_id]['title']} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("results", nargs="+", type=Path, help="JUnit XML or `go test -json` output files")
    parser.add_argument("--requirements", type=Path, default=Path("docs/requirements"))
    parser.add_argument("--output", type=Path, default=Path("docs/requirements/STATUS.md"))
    parser.add_argument("--check", action="store_true", help="exit 1 if --output is not up to date")
    args = parser.parse_args()

    for path in [args.requirements, *args.results]:
        if not path.exists():
            sys.exit(f"not found: {path}")

    requirements = load_requirements(args.requirements, args.output)
    status, tests, unknown = build_status(requirements, load_results(args.results))
    report = render(requirements, status, tests, unknown, args.output)

    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != report:
            sys.exit(f"{args.output} is stale; rerun without --check")
        return
    args.output.write_text(report, encoding="utf-8")


if __name__ == "__main__":
    main()
